/**
 * Состояние простого экрана выбора способа пополнения (задача #55).
 *
 * Здесь ровно одно правило, и оно — причина существования экрана целиком.
 *
 * ⚠️ Адрес `/balance/top-up` — публичный контракт с ботом: `miniapp_buttons.py`
 * маппит на него и кнопку «Пополнить баланс», и кнопку рассылки, а живые
 * производители — клавиатура уведомления об автоплатеже, уведомления мониторинга
 * и админские рассылки. Маршрут обязан оставаться живым; менять можно только то,
 * что на нём рендерится.
 *
 * ⚠️ А единственная функция экрана, которой нет у блока способов на балансе, —
 * перенос `amount` и `returnTo` на экран суммы. `amount` (недостающая сумма в
 * рублях) и `returnTo` (путь прерванной покупки) кладёт
 * `src/components/InsufficientBalancePrompt.tsx`, вызываемый из десяти мест
 * покупки, продления и допоплат; `returnTo` в одиночку кладут карточки истёкшей
 * подписки. Потеряв хвост, человек лишается предзаполнения недостающей суммы и
 * возврата к прерванной покупке — его выкинет на баланс, а покупку он будет
 * собирать заново.
 *
 * Модуль чистый и без импортов: компонентных тестов в проекте не бывает
 * (`vitest.config.ts` — `environment: 'node'`), и без такого модуля проброс
 * проверялся бы только руками на стенде.
 */

/**
 * Query-хвост для ссылки карточки способа: `?amount=…&returnTo=…`, любая
 * половина или пустая строка.
 *
 * `returnTo` через `getSafeRedirectPath` НЕ прогоняем — этим занимается экран
 * суммы (`src/simple/pages/TopUpAmount.tsx`, `handleSuccess`). Здесь задача одна:
 * не потерять параметр по дороге.
 *
 * Порядок параметров апстримный (`src/pages/TopUpMethodSelect.tsx`): сначала
 * `amount`, потом `returnTo`. Всё прочее из адреса не переносится — экран суммы
 * читает только эти два, а остальное там либо метки рекламных ссылок, либо
 * параметры возврата платёжного шлюза.
 */
export function resolveTopUpSearch(searchParams: URLSearchParams): string {
  const params = new URLSearchParams();
  const amount = searchParams.get('amount');
  const returnTo = searchParams.get('returnTo');

  if (amount) params.set('amount', amount);
  if (returnTo) params.set('returnTo', returnTo);

  const query = params.toString();

  // Пустой хвост — именно пустая строка, а не одинокий `?`: он остался бы в
  // истории и в ссылке, которой человек может поделиться.
  return query ? `?${query}` : '';
}
