import type { UiMode } from '@/store/mode';
import { matchPathList } from './routeMatch';

/**
 * Сквозной список: апстримные страницы, которые рисуются в ПРОСТОЙ оболочке.
 *
 * Третья ветка шва `ProtectedRoute`. Реестр (`routes.tsx`) подменяет страницу,
 * сквозной список — только оболочку: страница остаётся апстримной, но человек
 * не проваливается в экспертный вид, нажав «Подключить устройство», «Рефералы»,
 * «Профиль», «Информация» или карточку подарка. Все эти кнопки стоят на нашей же
 * простой главной, и до #64 каждая из них была выходом из простого режима.
 *
 * ⚠️ **Список — ровно для адресов, куда ведут НАШИ кнопки.** Отсюда и уход
 * `/wheel` в #66: владелец решил, что колесо фортуны в простом режиме не
 * используется вовсе, баннер с простой главной убран, и вести на этот адрес стало
 * нечему. Прямая ссылка работать не перестала — `/wheel` открывается апстримной
 * страницей в апстримной оболочке, как любой путь вне обоих списков. Решение
 * обратимо одной строкой в каждом месте: вернётся баннер — вернётся и запись
 * (сторож посылки живёт в `passthrough.test.ts`, «колеса в простом режиме нет
 * вовсе»).
 *
 * Решение владельца (19.08.2026) объявлено ВРЕМЕННЫМ: у страницы может
 * появиться своя простая версия позже. Обратный ход поэтому однострочный — путь
 * ПЕРЕЕЗЖАЕТ отсюда в реестр `routes.tsx`, а не копируется: путь в обоих списках
 * ловит `passthrough.test.ts` как ошибку конфигурации.
 *
 * ⚠️ **Только пути, строками, без единого импорта компонента.** Это не стиль, а
 * условие: простой слой не импортирует ничего из `src/pages/**`, поэтому гейт
 * границ (`scripts/check-mode-boundaries.mjs`) ради сквозного списка не
 * расширяется ни на одну запись — ни `OPEN_DIRS`, ни `INFRA_ALLOWLIST`.
 * Апстримную страницу подставляет сам `<Route>` в `App.tsx`; шву достаточно
 * знать, что путь сквозной.
 *
 * ⚠️ Путь пишется **буква в букву как в `App.tsx`** — сторож сравнивает строки,
 * а у апстрима параметр статьи зовётся `:slug`.
 *
 * ⚠️ Путь пишется строковым литералом в одну строку: `passthrough.test.ts`
 * сверяет состав списка с решением владельца, а `App.tsx` разбирает текстом.
 */
export const PASSTHROUGH_PATHS: string[] = [
  // «Подключить устройство» — главная CTA простой главной и страницы подписки.
  '/connection',
  // QR-код: первый клик внутри подключения.
  '/connection/qr',
  // Плитка «Рефералы» в верхней сетке простой главной.
  '/referral',
  '/referral/partner/apply',
  '/referral/withdrawal/request',
  // Пункт меню — и десктопного, и бургера: с #66 состав у них общий.
  '/profile',
  '/profile/accounts',
  // Тоже пункт обоих меню; туда же ведёт карточка FAQ из поддержки.
  '/info',
  // Статья FAQ — единственная запись с параметром.
  '/info/:slug',
  // Карточка ожидающего подарка на простой главной.
  '/gift',
  '/gift/result',
];

/**
 * Есть ли у пути сквозная запись.
 *
 * ⚠️ Матчинг переиспользован из `routeMatch.ts`, второго в проекте быть не
 * должно: там уже разобрана ловушка #53 — для `matchPath` литеральный сегмент
 * неотличим от параметра, поэтому литералы ранжируются выше записей с
 * параметром, а апстримные литералы из `UPSTREAM_LITERAL_PATHS` записи с
 * параметром не достаются вовсе.
 *
 * ⚠️ В отличие от реестра, промах здесь **не подменяет страницу** — он меняет
 * только оболочку. Цена ошибки ниже, но и молчаливее: неверное совпадение
 * выглядит как «страница почему-то в другой рамке», а не как сломанный экран.
 */
export function isPassthroughPath(pathname: string): boolean {
  return matchPathList(PASSTHROUGH_PATHS, pathname) !== null;
}

/**
 * Решение шва: рисовать ли апстримную страницу в простой оболочке.
 *
 * Режим — аргумент, а не хук, чтобы решение проверялось тестом напрямую:
 * `vitest.config.ts` апстримный (`environment: 'node'`), React в тестах не
 * рендерится, и правило «в экспертном режиме сквозной список не действует
 * вовсе» иначе осталось бы доказанным только разбором текста. Хук-обёртка —
 * `useSimplePassthrough` в точке входа `index.tsx`.
 */
export function shouldPassthrough(mode: UiMode, pathname: string): boolean {
  return mode === 'simple' && isPassthroughPath(pathname);
}
