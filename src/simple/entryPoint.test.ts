import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

/**
 * Сторож единственной точки входа простого режима (#51).
 *
 * `src/simple/index.tsx` объявлен единственной дверью, через которую апстримный
 * код обращается к простому режиму, и на импорте этой двери висит побочный
 * эффект — регистрация неймспейса локалей (`import './i18n'`). Оба факта живут
 * только в докстринге, а докстринг ничего не ломает.
 *
 * Цена расхождения известна по месту, из которого задача и выросла: шапки
 * (`AppShell.tsx`, `AppHeader.tsx`) сначала импортировали реестр напрямую —
 * `@/simple/routes`, — минуя `index.tsx`. Неймспейс при этом регистрировался,
 * потому что `App.tsx` отдельно импортирует `./simple`. То есть подпись кнопки
 * перехода в простой режим держалась на посторонней строчке в другом файле:
 * переехал бы тот импорт — и подпись выродилась бы в сырой ключ
 * `mode.toSimple`, со зелёной сборкой и зелёными тестами.
 *
 * Файл разбирается ТЕКСТОМ, не импортируется: `vitest.config.ts` задаёт
 * `environment: 'node'`, alias `@/` в тестах не работает, а импорт точки входа
 * потянул бы i18next, страницы и весь граф приложения. Тот же приём, что в
 * `src/simple/routes.test.tsx` и `src/store/expertModeToggle.test.ts`; цена
 * приёма та же — разбор видит только литералы, поэтому обязательна пара
 * «разбор удался».
 */
const ENTRY_FILE = resolve(__dirname, 'index.tsx');

const source = readFileSync(ENTRY_FILE, 'utf8');

/**
 * Комментарии выбрасываем до поиска: докстринг самой точки входа объясняет, зачем
 * там `import './i18n'` и реэкспорт, и цитирует обе строки. Без этого шага сторож
 * бумажный — цитаты в комментарии хватило бы, чтобы он остался зелёным при
 * пропавшем настоящем импорте (проверено мутацией: убрать строку из кода,
 * оставить в докстринге). Тот же приём, что в `src/simple/openDirsPurity.test.ts`
 * и `scripts/check-mode-boundaries.mjs`.
 */
function stripComments(code: string): string {
  return code.replace(/(^|\s)\/\*[\s\S]*?\*\//g, '$1').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

/** Код точки входа без комментариев — только он считается доказательством. */
const code = stripComments(source);

describe('src/simple/index.tsx — единственная точка входа простого режима', () => {
  it('разбор удался — файл прочитан и непустой', () => {
    // Без этой пары переименование точки входа дало бы вечно зелёный сторож:
    // проверки ниже искали бы подстроки в пустой строке… точнее, не искали бы
    // вовсе — readFileSync бросил бы, но именно поэтому факт чтения проверяется
    // отдельным тестом с внятным именем.
    expect(source.length, `пустой ${ENTRY_FILE}`).toBeGreaterThan(100);
  });

  it('регистрирует неймспейс локалей побочным эффектом импорта', () => {
    // Без этой строки подписи простого режима — включая подпись кнопки в
    // апстримной шапке — отрисуются сырыми ключами.
    expect(
      code,
      "потерян import './i18n' — неймспейс простого режима не зарегистрирован",
    ).toContain("import './i18n';");
  });

  it('реэкспортирует resolveSimpleRoute для апстримных шапок', () => {
    // Шапки спрашивают у реестра, есть ли у пути простая версия (#45), и делают
    // это через точку входа. Пропадёт реэкспорт — сборка шапок красная, но
    // соблазн «починить» её импортом из `@/simple/routes` велик, поэтому факт
    // реэкспорта записан отдельным тестом с объяснением.
    expect(code, 'в точке входа нет реэкспорта resolveSimpleRoute').toMatch(
      /export \{[^}]*\bresolveSimpleRoute\b[^}]*\} from '\.\/routes';/,
    );
  });
});
