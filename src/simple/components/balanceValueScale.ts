/**
 * Кегль цифры баланса — один на все экраны простого режима (#72, #73).
 *
 * ⚠️ Зачем правило вообще. Спека #72 требует двух вещей сразу: цифра на мобилке
 * встаёт в десктопный кегль (`text-5xl`, 48px) И «значение — одна строка, не
 * переносится и не режется; проверить на семизначной сумме при ширине 360px».
 * Совместить их постоянным кеглем нельзя: `formatAmount` для рубля отдаёт
 * `toFixed(2)` без разрядов, то есть семизначный баланс — это `1234567.00`,
 * десять знаков. В 48px они шире колонки узкого экрана, а карточка — это
 * `.bento-card` с `overflow: hidden`, так что лишнее не выпирает, а ОБРЕЗАЕТСЯ.
 * Молча и только у богатых: на стенде с трёхзначным балансом дефекта не видно.
 *
 * ⚠️ Почему не CSS. Ни `clamp()`, ни `cqi` не знают длины строки: подобранный
 * ими кегль срезал бы и короткие суммы, ради которых кегль и поднимали. Длина же
 * известна в момент рендера — по ней и выбираем ступень.
 *
 * ⚠️ Почему модуль отдельный и чистый. Виджет тянет `@/api` и `@/hooks`, то есть
 * его граф импортов упирается в alias `@/`, который в тестах не разрешается
 * (docs/architecture/two-modes.md, раздел «Тесты»). Чистый модуль тест зовёт
 * напрямую, поэтому всё, что можно проверить вызовом функции, из разметки
 * выносится сюда: сторож — `balanceValueScale.test.ts`.
 *
 * ⚠️ С #73 правило считает кегль ДЛЯ ВСЕХ ТРЁХ ЭКРАНОВ, а не только для акцентной
 * карточки главной, и на `/balance` оно заведомо консервативнее необходимого:
 * бюджеты ниже посчитаны по самой узкой колонке макета — по сетке
 * `sm:grid-cols-2` главной, — а на `/balance` и на экране суммы пополнения
 * карточка всегда во всю ширину страницы. Так и надо. Цель #73 — чтобы сумма НЕ
 * МЕНЯЛА размер при переходе главная → `/balance`: до задачи плоский тон шёл
 * литеральной парой `text-4xl sm:text-5xl`, и цифра прыгала с 48px на 36px.
 * «Оптимизация» кегля по месту вернёт ровно этот дефект, поэтому у бюджета один
 * источник, а не по одному на экран.
 *
 * ⚠️ ГЛАВНОЕ, и на этом первая версия правила уже ошиблась. Бюджет считается ПО
 * КАЖДОМУ брейкпоинту отдельно, потому что самая узкая колонка — НЕ мобильная.
 * На мобилке карточка занимает строку целиком (328px содержимого при 360px
 * экрана), а с `sm:` она встаёт в сетку из двух колонок, и на самой границе
 * брейкпоинта колонка даёт только 259px. Первая версия знала один бюджет —
 * мобильный — и разрешала в 48-м кегле восьмизначную строку (`12345.00`,
 * 249.6px): в мобильную строку та влезает, в колонку `sm` нет. Дефект тихий и
 * начинается с баланса в десять тысяч.
 *
 * ⚠️ Ошибка держалась на неверном сравнении в комментарии: 259px ширины
 * СОДЕРЖИМОГО карточки сопоставлялись с 264px бюджета ОДНОЙ ТОЛЬКО ЦИФРЫ, из
 * которого 23.6px уже вычтены под символ валюты и его отступ. Настоящее
 * расхождение было не 5px, а 29px, и покрывалось оно исключительно тем, что
 * `GLYPH_EM` завышен относительно живых метрик Manrope. То есть заявленного
 * запаса не было вовсе — при том что весь модуль построен на обратном принципе:
 * оценка обязана быть ВЕРХНЕЙ.
 *
 * ⚠️ Правило считает ХУДШИЙ случай внутри каждого брейкпоинта — ширину на его
 * нижней границе. Выше по ширине колонка только растёт, поэтому запас не
 * уменьшается. Значит на 390px и шире цифра иногда мельче, чем могла бы быть, —
 * это сознательный размен: «чуть мельче» человек не заметит, обрезанную сумму
 * заметит сразу.
 */

/**
 * Ширина знака относительно кегля — ВЕРХНЯЯ оценка для Manrope Bold.
 *
 * Точные метрики шрифта отсюда недоступны (модуль чистый, DOM в тестах нет),
 * поэтому берётся заведомо щедрая цифра: ошибка в большую сторону даёт кегль на
 * ступень мельче, ошибка в меньшую — обрезанную сумму.
 */
const GLYPH_EM = 0.65;

/** Кегль символа валюты — `text-2xl` рядом с цифрой. */
const CURRENCY_FONT_PX = 24;

/** Отступ символа валюты от цифры — `ml-2`. */
const CURRENCY_GAP_PX = 8;

/** Внутренние поля карточки: `--bento-padding` в `globals.css`, 20px на всех ширинах. */
const CARD_PADDING_PX = 20 * 2;

/** Зазор сетки баланса и рефералов — `gap-2.5`. */
const GRID_GAP_PX = 10;

/**
 * Сколько ширины остаётся самой цифре в колонке шириной `columnPx`.
 *
 * Символ валюты стоит в той же строке и переносу не подлежит, поэтому его ширина
 * вычитается из бюджета, а не прибавляется к цифре.
 */
function budgetFor(columnPx: number): number {
  return columnPx - CARD_PADDING_PX - CURRENCY_GAP_PX - CURRENCY_FONT_PX * GLYPH_EM;
}

/**
 * Ширина колонки, в которой стоит карточка баланса, на нижней границе каждого
 * брейкпоинта.
 *
 * Мобилка: самый узкий поддерживаемый экран 360px, `main` идёт с `px-4`, карточка
 * занимает строку целиком.
 * `sm` (640px): те же `px-4`, но сетка `sm:grid-cols-2 gap-2.5` — колонка вдвое ýже.
 * `lg` (1024px): `main` переключается на `lg:px-6`, сетка та же.
 */
const MOBILE_COLUMN_PX = 360 - 16 * 2;
const SM_COLUMN_PX = (640 - 16 * 2 - GRID_GAP_PX) / 2;
const LG_COLUMN_PX = (1024 - 24 * 2 - GRID_GAP_PX) / 2;

export interface BalanceValueStep {
  /** Утилита Tailwind, которую получает цифра, — вместе с префиксом брейкпоинта. */
  className: string;
  /** Её кегль в пикселях — им и считается ширина. */
  fontPx: number;
}

export interface BalanceValueBreakpoint {
  /** Префикс Tailwind без двоеточия; `base` — без префикса вовсе. */
  name: 'base' | 'sm' | 'lg';
  /** Сколько пикселей остаётся цифре на нижней границе брейкпоинта. */
  budgetPx: number;
  /** Ступени кегля, от крупной к мелкой. */
  steps: readonly BalanceValueStep[];
}

/**
 * Ступени кегля по брейкпоинтам.
 *
 * ⚠️ Классы записаны ЛИТЕРАЛАМИ, включая префикс, и собирать их шаблоном
 * (`` `${prefix}text-5xl` ``) нельзя: Tailwind сканирует исходники ТЕКСТОМ, и
 * класса, которого в тексте нет, не окажется и в CSS — кегль молча останется
 * дефолтным. Тот же приём и та же причина, что в `paymentMethodsBento.ts`.
 *
 * Лестница кеглей у всех брейкпоинтов одна и та же (48 → 36 → 30 → 24 → 20);
 * первая ступень — требование спеки, остальные существуют ровно затем, чтобы
 * длинная сумма осталась читаемой целиком. Нижняя ступень нужна не рублю
 * (`toFixed(2)` даёт десять знаков даже на миллионах), а локалям с разрядами:
 * `formatAmount` для IRR идёт через `toLocaleString('fa-IR')`, и там разделители
 * добавляют к строке треть длины.
 */
export const BALANCE_VALUE_BREAKPOINTS: readonly BalanceValueBreakpoint[] = [
  {
    name: 'base',
    budgetPx: budgetFor(MOBILE_COLUMN_PX),
    steps: [
      { className: 'text-5xl', fontPx: 48 },
      { className: 'text-4xl', fontPx: 36 },
      { className: 'text-3xl', fontPx: 30 },
      { className: 'text-2xl', fontPx: 24 },
      { className: 'text-xl', fontPx: 20 },
    ],
  },
  {
    name: 'sm',
    budgetPx: budgetFor(SM_COLUMN_PX),
    steps: [
      { className: 'sm:text-5xl', fontPx: 48 },
      { className: 'sm:text-4xl', fontPx: 36 },
      { className: 'sm:text-3xl', fontPx: 30 },
      { className: 'sm:text-2xl', fontPx: 24 },
      { className: 'sm:text-xl', fontPx: 20 },
    ],
  },
  {
    name: 'lg',
    budgetPx: budgetFor(LG_COLUMN_PX),
    steps: [
      { className: 'lg:text-5xl', fontPx: 48 },
      { className: 'lg:text-4xl', fontPx: 36 },
      { className: 'lg:text-3xl', fontPx: 30 },
      { className: 'lg:text-2xl', fontPx: 24 },
      { className: 'lg:text-xl', fontPx: 20 },
    ],
  },
];

/** Верхняя оценка ширины строки в пикселях при заданном кегле. */
export function balanceValueWidthPx(formatted: string, fontPx: number): number {
  return formatted.length * GLYPH_EM * fontPx;
}

/** Выбранная ступень каждого брейкпоинта — по одной на каждый, без пропусков. */
export interface BalanceValueChoice extends BalanceValueStep {
  name: BalanceValueBreakpoint['name'];
}

/**
 * Самая крупная ступень каждого брейкпоинта, при которой сумма влезает в его
 * колонку.
 *
 * Не влезает ни одна — берётся самая мелкая: класс нужен всегда, пустая строка в
 * `className` вернула бы кегль по умолчанию, то есть худший из возможных.
 */
export function resolveBalanceValueSteps(formatted: string): BalanceValueChoice[] {
  return BALANCE_VALUE_BREAKPOINTS.map((breakpoint) => {
    const fits = breakpoint.steps.find(
      (step) => balanceValueWidthPx(formatted, step.fontPx) <= breakpoint.budgetPx,
    );
    const step = fits ?? breakpoint.steps[breakpoint.steps.length - 1];

    return { name: breakpoint.name, className: step.className, fontPx: step.fontPx };
  });
}

/**
 * Готовая строка классов для разметки.
 *
 * Брейкпоинт, повторяющий кегль предыдущего, из выдачи выпадает: `sm:text-5xl`
 * рядом с `text-5xl` ничего не меняет и только шумит в разметке.
 */
export function resolveBalanceValueClass(formatted: string): string {
  const chosen = resolveBalanceValueSteps(formatted);

  return chosen
    .filter((step, index) => index === 0 || step.fontPx !== chosen[index - 1].fontPx)
    .map((step) => step.className)
    .join(' ');
}
