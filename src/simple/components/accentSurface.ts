/**
 * Акцентная поверхность простого режима — одна на все громкие элементы (#72).
 *
 * ⚠️ Зачем модуль вообще. До #72 поверхность жила в `connectButtonAccent.ts` и
 * принадлежала одной кнопке. Задача #72 отдаёт ту же заливку карточке баланса на
 * главной, и соблазн «скопировать четыре строчки» здесь смертельный: этот форк
 * уже проходил ровно этот путь. Кнопку «Подключить устройство» держали двумя
 * копиями, после #59 акцент достался одной из них, и разъехались они МОЛЧА — со
 * зелёной сборкой и зелёными тестами (#61). Поэтому заливка, тень и цвет «поверх
 * акцента» объявлены здесь ОДИН раз, а кнопка и виджет баланса их читают.
 *
 * ⚠️ Модуль чистый: ни React, ни `@/api`, ни `@/store`, ни типов. Причина —
 * граница alias: граф импортов кнопки и виджета дотягивается до `@/…`, который в
 * тестах не разрешается (docs/architecture/two-modes.md, раздел «Тесты»), а
 * чистый модуль тест зовёт напрямую. Поэтому всё, что можно проверить вызовом
 * функции, из разметки выносится сюда. Сторож —
 * `subscription/connectButtonAccent.test.ts`: он гоняет свои запреты и по выдаче
 * кнопки, и по значениям этого модуля.
 *
 * ⚠️ Значения — ПЕРЕМЕННЫЕ ТЕМЫ, а не литералы. Литеральные `#3B82F6`/`#1D4ED8`,
 * стоявшие в кнопке после #59, — это акцент ПО УМОЛЧАНИЮ
 * (`--color-accent-500: 59, 130, 246`, `src/styles/globals.css`), то есть акцент
 * переставал следовать палитре, стоило оператору сменить её в админке (#61).
 *
 * ⚠️ Шейды 600 и 800, а не 500 и 700 (#62). Владелец на стенде: «кислотно яркая,
 * в светлой теме вырвиглазно». Приглушается ТОН, а не вес — заливка остаётся
 * сплошной, поверхность остаётся самым громким элементом экрана. Заодно здесь не
 * бывает шейдов 300 и 400 ни у одной палитры: блок `.light` в `globals.css`
 * ремапит их через `!important`, а тот бьёт инлайн-переменные, которые
 * `applyThemeColors` ставит на `:root`, — в светлой теме перебивается не стиль, а
 * само значение. Сторож запрещает оба класса шейдов, а не конкретные поля.
 *
 * ⚠️ Почему инлайн-стилем, а не утилитами Tailwind. Утилиты рамки и свечения
 * (`border-accent-*`, `shadow-glow`) в светлой теме подавляются правилами
 * карточек — установлено в #52 и записано в каноне. Инлайн-стиль эти правила
 * перебить не могут в принципе, поэтому акцент виден в обеих темах.
 *
 * ⚠️ ИЗВЕСТНАЯ ГРАНИЦА, оставлена сознательно (переехала сюда из акцента кнопки
 * вместе с заливкой). `--color-on-accent` считается от ПЯТИСОТОГО шейда
 * (`src/hooks/useThemeColors.ts:242-243`), а заливка после #62 идёт по 600–800.
 * Пока акцент оператора тёмный (по умолчанию синий) надпись от углубления
 * заливки только выигрывает. Но если оператор выберет ОЧЕНЬ СВЕТЛЫЙ акцент,
 * `onColorFor` посчитает надпись тёмной по пятисотому, а восьмисотый шейд
 * тёмный — и контраст упадёт. Дешёвого обхода в границах простого режима нет:
 * держать один конец градиента на пятисотом запрещено решением #62 (это и есть
 * возврат яркости), а считать `--color-on-accent` от заливки — правка
 * `useThemeColors`, то есть общего с экспертным режимом кода. Всплывёт жалобой
 * на светлом акценте — чинить надо там. С #72 цена ошибки выросла ровно вдвое:
 * поверхность носят два элемента, а не один.
 */

/**
 * Цвет «поверх акцента» с запасным значением на первый кадр.
 *
 * ⚠️ Переменная, а не белый литерал. `src/hooks/useThemeColors.ts:242-243`
 * считает этот цвет из выбранной палитры ровно потому, что «захардкоженный белый
 * ломается, как только оператор выбирает светлый акцент». Запасное значение
 * `255, 255, 255` в `var()` нужно на первый кадр: переменную заводит
 * `applyThemeColors` из эффекта `ThemeColorsProvider`, а объявления по умолчанию
 * в `globals.css` у неё, в отличие от `--color-accent-*`, нет.
 */
export const ON_ACCENT = 'var(--color-on-accent, 255, 255, 255)';

/** Тёплый конец градиента заливки. */
const FILL_FROM = '--color-accent-600';
/** Глубокий конец градиента заливки. */
const FILL_TO = '--color-accent-800';

/**
 * Заливка акцентной поверхности.
 *
 * `alpha` приглушает ОБА конца градиента и нужен ровно одному состоянию — кнопке,
 * упёршейся в лимит устройств. Приглушение сделано прозрачностью, а не вторым
 * набором шейдов, именно поэтому: второй набор — это снова две копии, которые
 * разойдутся.
 */
export function accentFill(alpha?: number): string {
  const stop = (name: string) =>
    alpha === undefined ? `rgb(var(${name}))` : `rgba(var(${name}), ${alpha})`;

  return `linear-gradient(135deg, ${stop(FILL_FROM)}, ${stop(FILL_TO)})`;
}

/**
 * Тень ГЛУБИНЫ, а не ореол.
 *
 * ⚠️ Задана в покое, а не на `:hover`: на телефоне и внутри Telegram наведения не
 * существует, и элемент с акцентом «только под курсором» пролистывали (#61). Но
 * за громкость отвечает сплошная заливка, поэтому цветной ореол `0 6px 24px` в
 * #62 срезан — осталось короткое размытие тёмным шейдом.
 */
export const ACCENT_SHADOW = '0 2px 8px rgba(var(--color-accent-900), 0.25)';

/** Текст и иконки на заливке. */
export const ACCENT_FOREGROUND = `rgb(${ON_ACCENT})`;

/** Второстепенная подпись на заливке — то же значение, но тише. */
export const ACCENT_FOREGROUND_MUTED = `rgba(${ON_ACCENT}, 0.7)`;
