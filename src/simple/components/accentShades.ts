/**
 * Шейды акцента, которые в СВЕТЛОЙ теме употреблять нельзя (#59, #61, #62, #76).
 *
 * ⚠️ Модуль существует ради одного: список запрещённых шейдов в форке должен быть
 * ОДИН. До #76 он жил константами внутри `subscription/connectButtonAccent.test.ts`
 * и охранял ровно один экран. В #76 те же два запрета понадобились второму сторожу
 * — правилу `.light .btn-primary` в `src/styles/globals.css`, — и второй список
 * означал бы ровно то, чем этот форк уже обжигался дважды: копии расходятся молча,
 * со зелёной сборкой и зелёными тестами (#59 → #61, #72). Поэтому правило вынесено
 * сюда, а сторожа его читают.
 *
 * ⚠️ Модуль чистый: ни React, ни `@/…`, ни типов апстрима. Иначе его не смог бы
 * импортировать ни один тест — alias `@/` в vitest не разрешается
 * (docs/architecture/two-modes.md, раздел «Тесты»).
 *
 * Оба запрета — про КЛАСС, а не про конкретное поле или конкретный экран. Именно
 * поэтому они и переиспользуются: правило «нельзя вот этому полю» переезжать было
 * бы незачем.
 */

/**
 * Шейды статусных палитр, которые светлая тема ПОДМЕНЯЕТ.
 *
 * ⚠️ Подменяет через `!important` (`src/styles/globals.css`, блок `.light`), а тот
 * бьёт инлайн-переменные, которые `applyThemeColors` ставит на `:root`. То есть в
 * светлой теме перебивается НЕ СТИЛЬ, А САМА ПЕРЕМЕННАЯ, и приём «пишем инлайн,
 * значит светлая тема не помешает» здесь не работает вовсе. Утилиту Tailwind
 * (`bg-accent-400`) ремап уводит тем же способом и по той же причине.
 *
 * Список не выдуман: он сверяется с самим `globals.css` — сверка живёт в
 * `subscription/connectButtonAccent.test.ts` и остаётся в единственном экземпляре.
 * Начнёт апстрим ремапить ещё один шейд — сверка покраснеет, а не промолчит.
 */
export const LIGHT_REMAPPED_SHADES: ReadonlySet<string> = new Set(['300', '400']);

/**
 * Самый светлый акцентный шейд, которому в акцентных поверхностях есть место (#62).
 *
 * ⚠️ Правило от обратного, и оно закрывает КЛАСС, а не случай. Жалоба владельца
 * 18.08.2026 была не «пятисотый неудачен», а «кнопка кислотно яркая, в светлой теме
 * вырвиглазно». Яркость давали именно светлые шейды акцента, поэтому запрет стоит не
 * на конкретном поле заливки, а на любом употреблении шейда ниже шестисотого.
 */
export const MIN_ACCENT_SHADE = 600;

/**
 * Тело блока `.light` из переданного CSS — то место, где живут ремапы.
 *
 * ⚠️ Экспортируется ради сторожей: «разбор удался» им надо проверять на самом
 * разборе, а не на длине всего файла. `globals.css` весит десятки килобайт и
 * пройдёт любую проверку длины даже с вырезанным блоком `.light` — то есть такая
 * проверка непадаема и держит пару только на вид.
 */
export function lightBlock(css: string): string {
  return /\n\s*\.light\s*\{([\s\S]*?)\n\s*\}/.exec(css)?.[1] ?? '';
}

/**
 * Шейды палитр, которые блок `.light` в переданном CSS ремапит через `!important`.
 *
 * ⚠️ Вынесено сюда вместе с константой: список и его сверка с реальностью — одно
 * правило, и разъехаться они не должны так же, как не должны разъехаться копии
 * самого списка.
 */
export function lightRemappedShades(css: string): Set<string> {
  return new Set(
    [
      ...lightBlock(css).matchAll(
        /--color-(?:accent|warning|success|error)-(\d{2,3})\s*:[^;]*!important/g,
      ),
    ].map((found) => found[1]),
  );
}

/** Ремапится ли шейд светлой темой — то есть значит ли он в светлой теме другое. */
export function isLightRemappedShade(shade: string | number): boolean {
  return LIGHT_REMAPPED_SHADES.has(String(shade));
}

/** Годится ли акцентный шейд для громкой поверхности: не ремапится и не ярче #62. */
export function isAllowedAccentShade(shade: string | number): boolean {
  return !isLightRemappedShade(shade) && Number(shade) >= MIN_ACCENT_SHADE;
}
