/**
 * Бенто-раскладка карточек способов оплаты — «Баннер и полки» (задача #55).
 *
 * Вариант выбран владельцем 17.08.2026: акцентная карточка всегда отдельной
 * строкой во всю ширину, остальные — полками под ней, а ширина мелких подбирается
 * так, чтобы каждая полка была заполнена целиком. Пустых клеток не бывает ни при
 * каком числе способов; раскладки с жёсткой высотой отклонены — описания способов
 * приходят с бэкенда разной длины и правятся из админки.
 *
 * ⚠️ Чистый модуль, и это не украшение: компонентных тестов в проекте не бывает
 * (`vitest.config.ts` — `environment: 'node'`, ни jsdom, ни testing-library), а
 * alias `@/` в тестах не разрешается. Без такого модуля раскладка проверялась бы
 * только глазами. Разметка (`PaymentMethodsGrid.tsx`) результат ТОЛЬКО читает —
 * условий раскладки в JSX нет, этого требует спека.
 *
 * Здесь нет ни одного импорта: файл свободен и от приложения, и от react.
 */

/**
 * Колонок в сетке. Шесть, потому что делится и на 2, и на 3: полка из двух
 * карточек даёт пролёт 3, из трёх — пролёт 2, одиночка — 6.
 *
 * ⚠️ Число живёт здесь, а сама сетка объявлена классом `sm:grid-cols-6` в
 * `PaymentMethodsGrid.tsx`. Два места сверяет сторож
 * `paymentMethodsGrid.test.ts`: он читает `grid-cols-*` из разметки текстом и
 * требует совпадения с этой константой. Иначе смена числа колонок у контейнера
 * молча ломала бы «во всю ширину строки» — ровно на этом попались в #52.
 */
export const BENTO_COLUMNS = 6;

/** Пролёт карточки на каждом брейкпоинте, где сетка многоколоночная. */
export type MethodCardSpans = {
  sm: number;
  lg: number;
};

/**
 * Полки мелких карточек на `lg`: по три карточки в полке, а остаток разбирается
 * так, чтобы полка всё равно закрылась ровно.
 *
 * Числа в массиве — сколько КАРТОЧЕК в полке, не пролёт.
 *
 * ⚠️ Ветка `r % 3 === 1` — не оптимизация, а единственный способ обойтись без
 * дыры: остаток «одна карточка» после троек занял бы 2 колонки из 6. Поэтому одна
 * тройка разбирается на две двойки (`3 + 1 → 2 + 2`), и обе полки закрываются.
 * Исключение — `r === 1`: разбирать нечего, единственная карточка идёт во всю
 * ширину.
 */
function lgShelves(remaining: number): number[] {
  if (remaining <= 0) return [];
  if (remaining === 1) return [1];

  const remainder = remaining % 3;

  if (remainder === 0) {
    return Array<number>(remaining / 3).fill(3);
  }
  if (remainder === 2) {
    return [...Array<number>((remaining - 2) / 3).fill(3), 2];
  }

  return [...Array<number>((remaining - 4) / 3).fill(3), 2, 2];
}

/**
 * Полки мелких карточек на `sm`: по две, нечётный хвост — одиночкой во всю
 * ширину.
 *
 * ⚠️ Три карточки в полке здесь запрещены спекой: на 640-пиксельном экране это
 * по ~200 пикселей на карточку, куда не влезает ни название способа, ни диапазон
 * сумм.
 */
function smShelves(remaining: number): number[] {
  if (remaining <= 0) return [];

  const shelves = Array<number>(Math.floor(remaining / 2)).fill(2);
  if (remaining % 2 === 1) {
    shelves.push(1);
  }

  return shelves;
}

/**
 * Полки → пролёты: карточек в полке `size`, значит каждой достаётся
 * `BENTO_COLUMNS / size` колонок. Деление точное для 1, 2 и 3 — ровно те размеры
 * полок, которые выдают функции выше.
 */
function shelvesToSpans(shelves: number[]): number[] {
  return shelves.flatMap((size) => Array<number>(size).fill(BENTO_COLUMNS / size));
}

/**
 * Пролёты всех карточек в порядке списка способов.
 *
 * Нулевая карточка — акцентная: она занимает строку целиком на каждом
 * брейкпоинте. Остальные раскладываются полками, разными на `sm` и на `lg`.
 *
 * ⚠️ Акцент достаётся буквально первой карточке списка, доступность роли не
 * играет (решение владельца 17.08.2026, #52) — поэтому и растянута здесь именно
 * нулевая, без всяких условий. Перескочившая карточка уже не первая в сетке, и
 * растянуть её на строку, где первую колонку занимает приглушённая карточка,
 * нельзя: авто-раскладка унесла бы её на следующую строку и оставила дыру.
 *
 * Больше шести способов не особый случай: полки добираются тем же правилом.
 * Красивой раскладка при десяти способах быть не обязана, но дыр в ней нет.
 */
export function resolveMethodCardSpans(count: number): MethodCardSpans[] {
  if (count <= 0) return [];

  const remaining = count - 1;
  const sm = shelvesToSpans(smShelves(remaining));
  const lg = shelvesToSpans(lgShelves(remaining));

  return [
    { sm: BENTO_COLUMNS, lg: BENTO_COLUMNS },
    ...sm.map((span, index) => ({ sm: span, lg: lg[index] })),
  ];
}

/**
 * Классы пролётов — ЛИТЕРАЛАМИ, по одному на каждое возможное число колонок.
 *
 * ⚠️ Собрать класс шаблонной строкой (`` `sm:col-span-${span}` ``) нельзя:
 * Tailwind сканирует исходники текстом и такого класса не увидит — в собранном
 * CSS правила не будет, а сборка останется зелёной. Отсюда карты.
 */
export const SM_COL_SPAN_CLASS: Record<number, string> = {
  1: 'sm:col-span-1',
  2: 'sm:col-span-2',
  3: 'sm:col-span-3',
  4: 'sm:col-span-4',
  5: 'sm:col-span-5',
  6: 'sm:col-span-6',
};

export const LG_COL_SPAN_CLASS: Record<number, string> = {
  1: 'lg:col-span-1',
  2: 'lg:col-span-2',
  3: 'lg:col-span-3',
  4: 'lg:col-span-4',
  5: 'lg:col-span-5',
  6: 'lg:col-span-6',
};

/** Классы пролёта одной карточки для атрибута `className`. */
export function spanClasses(spans: MethodCardSpans): string {
  return `${SM_COL_SPAN_CLASS[spans.sm]} ${LG_COL_SPAN_CLASS[spans.lg]}`;
}
