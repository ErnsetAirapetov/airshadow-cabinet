import type { PaymentMethod } from '@/types';

/**
 * Правила блока способов оплаты: кто акцентный и куда ведёт карточка.
 *
 * ⚠️ Почему отдельный модуль (#58). Обе функции родились в
 * `src/simple/pages/balanceState.ts` — тогда их звала только страница баланса.
 * Потом блок способов стал общим компонентом (`PaymentMethodsGrid`), и
 * единственным потребителем обеих оказался он: компонент импортировал из модуля,
 * названного по ОДНОЙ из двух своих страниц, то есть слой компонентов зависел от
 * состояния страницы. Цикла не было и гейт молчал, но адрес врал про владельца
 * правил. Теперь правила лежат рядом с их единственным потребителем.
 *
 * Раскладка того же блока живёт в соседнем `paymentMethodsBento.ts` — он
 * намеренно без единого импорта, поэтому тип `PaymentMethod` здесь, а не там.
 *
 * ⚠️ Чистый модуль, и это не украшение: alias `@/` в тестах не разрешается, а
 * `import type` стирается при трансформации — поэтому тип алиасом импортировать
 * можно, а всё остальное нет.
 */

/**
 * id способа оплаты, чья карточка рисуется акцентной.
 *
 * ⚠️ Акцент у **буквально первой** карточки списка, доступность роли не играет
 * (решение владельца 17.08.2026, задача #52). Прежде акцент уходил первому
 * ДОСТУПНОМУ способу — исключение убрано целиком, возвращать его нельзя.
 *
 * Почему убрано: перескочившая карточка уже не первая в сетке, а растянуть её на
 * всю ширину строки, где первую колонку занимает приглушённая карточка, нельзя —
 * авто-раскладка уносила её на следующую строку, и хвост первой строки оставался
 * пустым. С «первым элементом» дыра исчезает по построению: растянутой карточке
 * всегда есть где развернуться.
 *
 * Принятая цена, менять её обратно нельзя: если бэкенд отдаст первым недоступный
 * способ, акцент окажется на приглушённой некликабельной карточке. Владелец знает
 * и согласен. Смягчено ровно одним — hover-варианты акцента страница даёт только
 * доступной карточке, чтобы под курсором не подсвечивалось то, на что нельзя
 * нажать.
 *
 * Порядок списка задаёт бэкенд админским `sort_order`, и это единственный сигнал
 * приоритета в контракте: полей `order`, `priority` и `is_recommended` в
 * `PaymentMethod` нет. Значит «первый» здесь — первый по порядку бэкенда.
 *
 * Пустой список или ещё не пришедшие данные — `null`: акцента нет ни у кого, сетка
 * рисуется как обычно.
 */
export function resolveAccentedMethodId(methods: PaymentMethod[] | undefined): string | null {
  return methods?.[0]?.id ?? null;
}

/**
 * Экран суммы пополнения — апстримный маршрут `/balance/top-up/:methodId`.
 *
 * `search` — готовый query-хвост вида `?amount=…&returnTo=…` или пустая строка
 * (задача #55). Нужен экрану выбора способа: `amount` и `returnTo` приходят на
 * него от `InsufficientBalancePrompt` и обязаны доехать до экрана суммы, иначе
 * теряются предзаполнение недостающей суммы и возврат к прерванной покупке.
 * Страница баланса зовёт без хвоста — там этих параметров нет.
 */
export function topUpHref(methodId: string, search = ''): string {
  return `/balance/top-up/${methodId}${search}`;
}
