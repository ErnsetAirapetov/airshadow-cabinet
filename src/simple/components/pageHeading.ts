/**
 * Высота блока заголовка страницы простого режима (#73).
 *
 * ⚠️ Зачем константа. Карточка баланса стоит на главной и на `/balance` под
 * блоком заголовка, и при переходе между экранами она «прыгала»: на главной над
 * ней двухстрочное приветствие, на `/balance` — заголовок в одну строку. Разница
 * тихая — обе страницы по отдельности выглядят правильно, видно её только в
 * движении. Лечится это не подгонкой текста, а фиксированной минимальной высотой
 * блока, ОДНОЙ на обе страницы: два литерала в двух файлах разъедутся при первой
 * же правке — так этот форк уже терял кнопку подключения (#59 → #61).
 *
 * ⚠️ Ту же высоту берёт и сама главная. У приветствия две ветки: с именем оно
 * двухстрочное, без имени (`dashboard.welcomeNoName`) — однострочное. Без общей
 * высоты карточка уезжала бы уже между двумя состояниями одного экрана.
 *
 * Откуда числа — высота ДВУХСТРОЧНОГО приветствия, самой высокой из веток:
 *
 * | | строка «Добро пожаловать» | имя | итого |
 * |---|---|---|---|
 * | мобилка | `text-base`, lh 24px | `text-2xl`, lh 32px | **56px** |
 * | `sm:` | `sm:text-lg`, lh 28px | `sm:text-3xl`, lh 36px | **64px** |
 *
 * Кегли — стандартная шкала Tailwind: `tailwind.config.js` переопределяет в
 * `fontSize` единственный размер `2xs`, остальные идут как есть.
 *
 * ⚠️ `min-h`, а не `h`: заголовок длиннее двух строк (узкий экран, длинное имя,
 * другая локаль) обязан раздвинуть блок, а не быть обрезанным. Позиция карточки
 * в этом редком случае уедет — но уедет ОДИНАКОВО, потому что высоту в обоих
 * местах задаёт одно правило.
 *
 * ⚠️ Классы записаны литералами: Tailwind сканирует исходники текстом, и класса,
 * собранного шаблоном (`` `min-h-[${px}px]` ``), в CSS не окажется — блок молча
 * останется нулевой высоты. Тот же приём и та же причина, что в
 * `balanceValueScale.ts` и `paymentMethodsBento.ts`.
 */
export const PAGE_HEADING_BLOCK = 'min-h-[56px] sm:min-h-[64px]';
