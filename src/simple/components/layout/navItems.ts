/**
 * Состав навигации простого режима — ОДИН список на три места (#66).
 *
 * До #66 состав был записан трижды: десктопное меню в `SimpleShell.tsx`, нижнее
 * меню в `MobileBottomNav.tsx`, бургер в `SimpleHeader.tsx`. Копии разъехались
 * молча, при зелёной сборке: на десктопе шесть пунктов, в бургере два. Владелец
 * увидел это на стенде и потребовал единообразия — «что в меню на десктопе, то и
 * в мобилке доступно для перехода. То что это дублируется в меню снизу —
 * неважно». Дописать недостающие пункты в бургер третьим перечнем значило бы
 * разъехаться снова, поэтому перечень остался один.
 *
 * Кто что берёт:
 *
 *   - десктопное меню и бургер — **весь** список, целиком и в этом порядке;
 *   - нижнее меню — производное `SIMPLE_BOTTOM_NAV_ITEMS`, то есть подмножество
 *     по признаку `inBottomNav`, а не свой перечень.
 *
 * Пункт администратора сюда не входит: он условный (`isAdmin`), рисуется особым
 * видом и в нижнее меню не попадает вовсе.
 *
 * ⚠️ **Модуль чистый: ни одного импорта из `@/**`, ни иконок, ни `t`.** Это не
 * стиль, а условие проверяемости — то же, что у `passthrough.ts`:
 * `vitest.config.ts` апстримный (`environment: 'node'`, alias `@/` нет), и
 * модуль с иконками в тест импортом не втащить, сторожу состава остался бы
 * только разбор текста. Поэтому подпись здесь — **ключ локали**, переводит
 * потребитель, а иконки живут рядом в `navIcons.ts` картой по путям.
 *
 * ⚠️ **Ключ может быть апстримным или нашим (`simple`), и различает их поле
 * `ownLabel` (задача #75) — а не путь и не имя ключа.** До #75 подпись всегда
 * читалась апстримным `t`, а у новостей не нашлось апстримного ключа со
 * значением «Новости»: есть только `admin.nav.news` и
 * `profile.notifications.news`, чужая семантика. Заводить его в нашем
 * неймспейсе можно, но тогда потребитель обязан узнать, каким `t` печатать
 * пункт. Признак стоит в самих данных, а не в потребителе: третий литеральный
 * список путей вида «эти три — наши» разъехался бы с составом ровно как
 * разъезжались перечни до #66. Модуль по-прежнему не пишет `simple` литералом
 * нигде — константу неймспейса резолвит и импортирует потребитель.
 */
export interface SimpleNavItem {
  /** Путь как в `App.tsx` и реестре `routes.tsx`. */
  readonly path: string;
  /** Ключ подписи — апстримный или наш, смотря по `ownLabel`. */
  readonly labelKey: string;
  /**
   * `true` — `labelKey` живёт в НАШЕМ неймспейсе (`simple`), печатать `tSimple`.
   * Не указан или `false` — апстримная локаль, неймспейс по умолчанию, `t`.
   */
  readonly ownLabel?: boolean;
  /** Стоит ли пункт ещё и в нижнем меню на мобильном. */
  readonly inBottomNav: boolean;
}

/**
 * Пункты простого режима в порядке показа — решение владельца, а не догадка
 * исполнителя. Состав сверяется целиком в `navItems.test.ts`.
 */
export const SIMPLE_NAV_ITEMS = [
  { path: '/', labelKey: 'nav.dashboard', inBottomNav: true },
  { path: '/subscriptions', labelKey: 'nav.subscription', inBottomNav: true },
  { path: '/balance', labelKey: 'nav.balance', inBottomNav: true },
  { path: '/support', labelKey: 'nav.support', inBottomNav: true },
  { path: '/profile', labelKey: 'nav.profile', inBottomNav: false },
  { path: '/info', labelKey: 'nav.info', inBottomNav: false },
  // ⚠️ Владелец потребовал просто «Новости», а не «Новости и обновления»
  // (#75). Апстримный `news.title` держит вторую формулировку, и трогать
  // апстримные локали канон запрещает; подходящего апстримного ключа со
  // значением «Новости» тоже нет — есть только `admin.nav.news` и
  // `profile.notifications.news`, чужая семантика. Поэтому `labelKey` здесь —
  // ключ НАШЕГО неймспейса (`ownLabel: true`), с тем же именем `news.title`,
  // что и у апстримного (это норма — см. docs/architecture/two-modes.md,
  // «Локали»), но своим текстом на обоих языках. Заголовок страницы
  // (`pages/News.tsx`) читает тот же ключ тем же `tSimple`, так что подпись
  // пункта и заголовок разъехаться не могут.
  //
  // Пункт стоит последним и БЕЗ `inBottomNav`: нижняя панель остаётся четвёркой
  // (решение владельца, #74). Позиция в списке меняется одной строкой.
  { path: '/news', labelKey: 'news.title', ownLabel: true, inBottomNav: false },
] as const satisfies readonly SimpleNavItem[];

/**
 * Путь пункта простого режима — тип выведен из списка, а не переписан руками.
 *
 * Ради него список и объявлен `as const`: `navIcons.ts` типизирует карту иконок
 * как `Record<SimpleNavPath, …>`, и пункт, добавленный в список без иконки, не
 * собирается вовсе. Сторож полноты — `tsc`, а не тест.
 */
export type SimpleNavPath = (typeof SIMPLE_NAV_ITEMS)[number]['path'];

/**
 * Нижнее меню — подмножество общего списка, вычисленное признаком.
 *
 * Это те же объекты, а не копии: `navItems.test.ts` сверяет по ссылке, потому
 * что копия прошла бы сверку путей и снова стала бы вторым источником истины.
 */
export const SIMPLE_BOTTOM_NAV_ITEMS: readonly (typeof SIMPLE_NAV_ITEMS)[number][] =
  SIMPLE_NAV_ITEMS.filter((item) => item.inBottomNav);

/**
 * Подсвечен ли пункт на текущем адресе.
 *
 * Предикат тоже был записан трижды, и копия в бургере отличалась: без особого
 * случая для `/`. Пока главной в бургере не было, отличие ничего не портило — с
 * шестью пунктами `startsWith('/')` подсветил бы сразу все.
 *
 * Совпадение по префиксу для остальных пунктов намеренное: за «балансом» стоит
 * пополнение из трёх экранов, за «подпиской» — покупка и продление, и пункт меню
 * обязан оставаться подсвеченным внутри своего поддерева.
 */
export function isSimpleNavActive(pathname: string, path: string): boolean {
  return path === '/' ? pathname === '/' : pathname.startsWith(path);
}

/**
 * Подпись пункта — каким переводчиком её печатать, решает `ownLabel` (#75), а
 * не сам потребитель. Общая функция вместо копии условия в каждом месте — та
 * же причина, что у `isSimpleNavActive` выше: три места, решающие одно и то же
 * порознь, однажды расходятся молча, при зелёной сборке.
 *
 * Переводчики приходят параметрами, а не импортом: модуль остаётся чистым
 * (см. докстринг файла) — ни `useTranslation`, ни `SIMPLE_NS` он не знает,
 * только то, что для одних пунктов нужен один `t`, а для других — другой.
 */
export function resolveNavLabel(
  item: Pick<SimpleNavItem, 'labelKey' | 'ownLabel'>,
  t: (key: string) => string,
  tSimple: (key: string) => string,
): string {
  return item.ownLabel ? tSimple(item.labelKey) : t(item.labelKey);
}
