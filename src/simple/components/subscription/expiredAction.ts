import type { Subscription } from '@/types';
import { PURCHASE_ROUTE, paymentRoute } from './purchaseCta';

/**
 * Чистая логика единственной кнопки истёкшей платной подписки (задачи #65, #70).
 *
 * ⚠️ Модуль чистый: ни React, ни `@/api`, ни `@/store`. Разметка блока —
 * тонкая оболочка над ним, потому что компонентных тестов в проекте не бывает
 * (docs/architecture/two-modes.md, раздел «Тесты»). До #65 всё это ветвление
 * жило разметкой карточки главной, то есть проверить его было нечем.
 *
 * ⚠️ БАЛАНСА ЗДЕСЬ НЕТ ВОВСЕ, и это суть #70. Раньше рядом жил порог
 * `hasBalanceForRenew` («есть ли хоть рубль») и решение «продлить или
 * пополнить»; цену продления порог не знал и знать не мог — она приходит из
 * `renewal-options` либо из каталога тарифа и зависит от выбранного срока.
 * Поэтому обе подписи кнопки врали: при 100 ₽ она обещала продление, которого
 * не будет, при нуле — требовала пополнения, не называя суммы.
 *
 * Владелец решил иначе: кнопка ВЕДЁТ НА ЭКРАН ОПЛАТЫ, где цены известны и уже
 * работает механизм «не хватает столько-то, пополнить» — отказ
 * `insufficient_funds` с полем `missing_amount` ловится в
 * `pages/SubscriptionPayment.tsx` и печатается `InsufficientBalancePrompt`
 * вместе со ссылкой на пополнение с подставленной суммой. Вернуть сюда порог
 * нечем: у `resolveExpiredRenewOperation` нет входа для баланса.
 */

/**
 * Суточный тариф с остановленными списаниями — «приостановлена», а не «истекла».
 *
 * ⚠️ Условие спрашивают двое: выбор операции ниже (снять с паузы, а не покупать
 * заново) и заголовок карточки на главной («Подписка приостановлена»). Второй
 * записи этого условия быть не должно: заголовок и действие разъехались бы
 * молча — кнопка «Возобновить» под заголовком «Подписка истекла».
 */
export function isPausedDailySubscription(subscription: Subscription): boolean {
  return Boolean(subscription.is_daily) && subscription.status === 'disabled';
}

/**
 * Статусы, при которых бэкенд ОТКАЗЫВАЕТ продлевать подписку, — копия множества
 * `_non_renewable` из репозитория бота (задача #67).
 *
 * ⚠️ ИСТОЧНИК, а не догадка: `remnawave-bedolaga-telegram-bot`,
 * `app/cabinet/routes/subscription_modules/renewal.py:130-136` —
 * `_non_renewable = {SubscriptionStatus.DISABLED.value, SubscriptionStatus.PENDING.value}`,
 * и при совпадении эндпоинт продления отвечает 400 с текстом
 * `Cannot renew subscription with status: <статус>`. Отказ намеренный и явный,
 * то есть чинить его надо на нашей стороне, а не обходить повтором запроса.
 *
 * ⚠️ Сверять по полю `status` МОЖНО ТОЧНО, гадать не нужно: в ответе API это
 * поле — `actual_status` (`subscription_modules/helpers.py:205`), ровно то
 * значение, по которому бэкенд и проверяет.
 *
 * ⚠️ После #70 этот список НЕ решает, куда вести человека: адрес у обеих
 * навигационных веток один. Он решает, каким СЛОВОМ подписана кнопка, и
 * остаётся нужен `pages/paymentState.ts`, где по нему выбирается источник цен.
 */
export const NON_RENEWABLE_STATUSES = ['disabled', 'pending'] as const;

/** Продление этой подписке бэкенд запретил — см. `NON_RENEWABLE_STATUSES`. */
export function isNonRenewableStatus(subscription: Subscription): boolean {
  return (NON_RENEWABLE_STATUSES as readonly string[]).includes(subscription.status);
}

/**
 * Что делает единственная кнопка блока.
 *
 * Размеченное объединение, а не флаги: у ветки «снять с паузы» нет адреса, а у
 * навигационных нет ничего, чем разметка могла бы позвать оплату — ни дней, ни
 * тарифа. Позвать её по недосмотру попросту нечем.
 *
 * ⚠️ ПОЧЕМУ НАВИГАЦИОННЫХ ВИДОВ ДВА, а адрес у них один. Различаются они только
 * подписью, и это не украшение: «Оформить подписку» у непродлеваемого статуса —
 * формулировка, согласованная владельцем в #67 и переведённая на оба языка, а
 * «Продлить» у обычной истёкшей — решение владельца от 19.08.2026 (#65). #70
 * сравняла адреса, но слова не отменяла. Схлопни их в один вид — одна из двух
 * согласованных подписей пропала бы молча, при зелёной сборке.
 */
export type ExpiredRenewOperation =
  /** Суточный тариф на паузе: возобновление списаний, а не покупка срока. */
  | { kind: 'resumeDaily' }
  /** Обычная истёкшая подписка — переход на оплату, подпись «Продлить». */
  | { kind: 'openPayment'; to: string }
  /** Непродлеваемый статус — тот же переход, подпись «Оформить подписку» (#67). */
  | { kind: 'openPurchase'; to: string };

/**
 * Куда ведёт кнопка блока — ОДНА функция маршрута на обе навигационные ветки.
 *
 * ⚠️ Литерала адреса в разметке нет и быть не должно: сюда ведут оба входа
 * простого режима — кнопка продления активной подписки
 * (`purchaseCta.resolveAllSubscriptionActions`) и кнопка истёкшей. До #69 второй
 * вход вёл в витрину, и владелец забраковал ровно это расхождение; две копии
 * литерала повторили бы его молча.
 *
 * Без `id` собрать адрес нечем — `id` приходит от API, и нулевой означает
 * «строки нет», а `/subscriptions/0/renew` вёл бы в никуда. Тогда остаётся
 * витрина.
 */
function expiredPaymentRoute(subscription: Subscription): string {
  return subscription.id ? paymentRoute(subscription.id) : PURCHASE_ROUTE;
}

/**
 * Что делает кнопка: возобновляет суточную подписку или ведёт на оплату.
 *
 * ⚠️ ПЕРЕХОД БЕЗУСЛОВЕН (#70). Ни баланс, ни доступность тарифа, ни право на
 * продление здесь больше не проверяются — с этим разбирается сам экран оплаты
 * (`pages/paymentState.ts`): продлеваемый статус платит продлением,
 * `disabled`/`pending` — покупкой своего тарифа, отвалившийся тариф уводит в
 * сетку выбора с баннером. Проверять то же самое ещё и здесь значило бы завести
 * второе правило, которое разъедется с первым молча.
 *
 * ⚠️ ПОРЯДОК ВЕТОК — часть правила. Пауза стоит ПЕРВОЙ: у приостановленного
 * суточного тарифа статус тоже `disabled`, и попади он ниже — человек, всего
 * лишь остановивший списания, уезжал бы покупать тариф заново вместо
 * возобновления. `togglePause` для него бэкендом разрешён и проверен (#65).
 *
 * ⚠️ ПРО `is_daily_paused` У ИСТЁКШЕЙ ПОДПИСКИ — вопрос закрыт, пересматривать
 * не нужно. Опасение «переход не снимет флаг, автосписание останется
 * выключенным» проверено ПО КОДУ БЭКЕНДА 19.08.2026 (репозиторий
 * `remnawave-bedolaga-telegram-bot`) и НЕ подтвердилось:
 * `app/cabinet/routes/subscription_modules/purchase.py:945-948` — оплата
 * тарифа выставляет `last_daily_charge_at = now` и `is_daily_paused = False`;
 * `daily.py:61-72` — `togglePause` приводит к тому же. Оба пути одинаково
 * возвращают службу, поэтому `isPausedDailySubscription` НЕ расширяется до
 * `is_daily_paused`: это было бы решение про поведение бэкенда, а не про
 * разметку, и в задаче его нет.
 */
export function resolveExpiredRenewOperation(subscription: Subscription): ExpiredRenewOperation {
  if (isPausedDailySubscription(subscription)) {
    return { kind: 'resumeDaily' };
  }

  const to = expiredPaymentRoute(subscription);

  if (isNonRenewableStatus(subscription)) {
    return { kind: 'openPurchase', to };
  }

  return { kind: 'openPayment', to };
}

/**
 * Короткое «Продлить» — подпись кнопки на главной, где она стоит в тесной
 * плитке рядом с суммой баланса. Ключ апстримный, из неймспейса `translation`.
 */
export const DEFAULT_RENEW_LABEL_KEY = 'dashboard.expired.quickRenew';

/**
 * «Продлить подписку» — подпись на странице подписки, где кнопка идёт во всю
 * ширину (решение владельца от 19.08.2026: критерий #65 требует именно этой
 * формулировки, а на главной остаётся короткая).
 *
 * ⚠️ Ключ НАШ, поэтому с префиксом неймспейса: строки простого режима живут в
 * `src/simple/locales/*.json` под неймспейсом `simple`, а блок зовёт `t()`
 * одного инстанса и для апстримного ключа выше. Без префикса на кнопке
 * напечатается сам ключ — молча, при зелёной сборке; резолв обеих подписей
 * проверяется настоящим i18next в `expiredAction.test.ts`.
 */
export const PAGE_RENEW_LABEL_KEY = 'simple:subscription.expiredRenewAction';

/**
 * «Оформить подписку» — подпись перехода у непродлеваемого статуса (#67).
 *
 * ⚠️ Ключ АПСТРИМНЫЙ и ровно тот, что стоял на этой кнопке до #65
 * (`purchaseCta.ts`, прежняя ветка истёкшей подписки). Своей строки задача не
 * заводит: формулировка уже согласована владельцем и переведена на оба языка.
 */
export const PURCHASE_LABEL_KEY = 'subscription.getSubscription';

/**
 * Подписи, которые местом вызова НЕ подменяются: они говорят не про продление.
 *
 * ⚠️ Таблицей, а не цепочкой тернарников: вид операции здесь ровно один раз
 * сопоставлен со своей подписью, и новая ветка операции без подписи не
 * потеряется молча — она просто не попадёт сюда и получит `renewLabelKey`,
 * что видно перебором в тестах.
 */
const FIXED_LABEL_KEYS: Partial<Record<ExpiredRenewOperation['kind'], string>> = {
  resumeDaily: 'dashboard.suspended.resume',
  openPurchase: PURCHASE_LABEL_KEY,
};

/**
 * Подпись кнопки: снятие с паузы — «Возобновить», непродлеваемый статус —
 * «Оформить подписку», остальное — «Продлить».
 *
 * ⚠️ `renewLabelKey` — способ развести подписи ДВУХ мест вызова, не разводя сам
 * блок: место вызова передаёт свой ключ, ветки «на главной / на странице» внутри
 * блока нет. Ровно так же у общей кнопки подключения разведён `className` (#61).
 *
 * ⚠️ На снятие с паузы и на непродлеваемый статус подмена НЕ действует: в первом
 * случае списания всего лишь остановлены, во втором продление бэкендом
 * запрещено, и «Продлить подписку» на такой кнопке обещало бы ровно то, что не
 * работает.
 */
export function resolveExpiredActionLabelKey(
  operation: ExpiredRenewOperation,
  renewLabelKey: string = DEFAULT_RENEW_LABEL_KEY,
): string {
  return FIXED_LABEL_KEYS[operation.kind] ?? renewLabelKey;
}
