/**
 * Акцент кнопки «Подключить устройство» (задачи #59, #61).
 *
 * ⚠️ Модуль чистый: ни React, ни `@/api`, ни `@/store`, ни даже типы. Кнопка —
 * тонкая оболочка над ним, потому что компонентных тестов в проекте не бывает
 * (`environment: 'node'`, alias `@/` в тестах не разрешается,
 * docs/architecture/two-modes.md, раздел «Тесты»). Всё, что здесь ветвится,
 * проверяется вызовом функции, а не чтением разметки.
 *
 * ⚠️ Почему инлайн-стиль, а не утилиты-классы. Утилиты рамки и свечения
 * (`border-accent-*`, `shadow-glow`) в светлой теме подавляются правилами
 * карточек — установлено в #52 и записано в каноне. Инлайн-стиль светлотемные
 * правила перебить не могут в принципе, поэтому акцент виден в обеих темах.
 *
 * ⚠️ НО ИНЛАЙН НЕ ЗАЩИЩАЕТ ОТ ПОДМЕНЫ САМОЙ ПЕРЕМЕННОЙ, и на этом здесь уже
 * поскользнулись. Блок `.light` в `globals.css` ремапит третьи и четвёртые
 * шейды ВСЕХ статусных палитр через `!important`, а тот бьёт инлайн-переменные,
 * которые ставит `applyThemeColors` на `:root`. То есть перебивается не стиль, а
 * значение: `rgb(var(--color-warning-400))` в светлой теме превращается в
 * `--color-warning-700`. Отсюда правило: в этом модуле не бывает шейдов 300 и
 * 400 — ни у акцента, ни у статусных палитр. Сторож запрещает их классом, а не
 * поимённо, и сверяет список ремапящихся шейдов с самим `globals.css`.
 *
 * ⚠️ Почему значения — ПЕРЕМЕННЫЕ ТЕМЫ, а не литералы. Ограничение #52 касается
 * только утилит-классов; на содержимое инлайн-стиля оно не распространяется.
 * Литеральные `#3B82F6`/`#1D4ED8`, стоявшие здесь после #59, — это акцент ПО
 * УМОЛЧАНИЮ (`--color-accent-500: 59, 130, 246`, `src/styles/globals.css:167`),
 * то есть кнопка переставала следовать палитре, стоило оператору сменить её в
 * админке (#61). `--color-accent-500` и `--color-accent-700` в светлой теме не
 * ремапятся — `.light` трогает только `300` и `400`, — так что тон стабилен и
 * без литералов. Ровно поэтому взяты пятисотый и семисотый, а не четырёхсотый.
 *
 * ⚠️ Текст и иконка — `--color-on-accent`, а не белый литерал.
 * `src/hooks/useThemeColors.ts:242-243` считает этот цвет из выбранной палитры
 * ровно потому, что «захардкоженный белый ломается, как только оператор выбирает
 * светлый акцент». Запасное значение `255, 255, 255` в `var()` нужно на первый
 * кадр: переменную заводит `applyThemeColors` из эффекта `ThemeColorsProvider`,
 * а объявления по умолчанию в `globals.css` у неё, в отличие от
 * `--color-accent-*`, нет.
 *
 * ⚠️ Свечение задано В ПОКОЕ, а не на `:hover`. Прежняя кнопка светилась только
 * под курсором (`.hover-border-gradient:hover` в globals.css), а на телефоне и
 * внутри Telegram наведения не существует — от акцента оставалась рамка в
 * полтора пикселя, и кнопку пролистывали.
 *
 * ⚠️ Единственный аргумент — состояние лимита устройств. Зона расхода трафика в
 * выдачу не входит: кнопка меняла тон по причине, к действию не относящейся
 * (то же правило «не красить действия статусным цветом», по которому тон убрали
 * из плитки тарифа в `SubscriptionCardActive`).
 */

/** Цвет «поверх акцента» с запасным значением на первый кадр. */
const ON_ACCENT = 'var(--color-on-accent, 255, 255, 255)';

export interface ConnectButtonAccent {
  /** Заливка кнопки. */
  background: string;
  /** Свечение В ПОКОЕ. `'none'` — только для состояния «лимит устройств». */
  boxShadow: string;
  /** Подложка иконки на заливке. */
  iconBackground: string;
  /** Текст заголовка и сама иконка. */
  foreground: string;
  /** Второстепенная подпись под заголовком. */
  foregroundMuted: string;
  /** Занятый слот индикатора устройств. */
  indicatorOn: string;
  /** Свободный слот индикатора устройств. */
  indicatorOff: string;
  /** Свечение занятого слота. */
  indicatorGlow: string;
  /** Дорожка индикатора при большом лимите устройств. */
  indicatorTrack: string;
  /** Подпись «лимит устройств достигнут» — предупреждающий тон. */
  limitNotice: string;
}

/** Общая для обоих состояний часть: всё, что лежит ПОВЕРХ заливки. */
const ON_FILL = {
  foreground: `rgb(${ON_ACCENT})`,
  foregroundMuted: `rgba(${ON_ACCENT}, 0.7)`,
  indicatorOn: `rgb(${ON_ACCENT})`,
  indicatorOff: `rgba(${ON_ACCENT}, 0.28)`,
  indicatorGlow: `0 0 6px rgba(${ON_ACCENT}, 0.55)`,
  indicatorTrack: `rgba(${ON_ACCENT}, 0.24)`,
  // ⚠️ Двухсотый, а не четырёхсотый: подпись лежит НА АКЦЕНТНОЙ ЗАЛИВКЕ, а
  // `--color-warning-400` в светлой теме подменяется семисотым — тёмно-оранжевый
  // на синем даёт контраст 1.37, надпись исчезает, и состояние «упёрлись в
  // лимит» перестаёт отличаться от рабочего. Двухсотый `.light` не трогает:
  // 2.95 на заливке в обеих темах (прежний литерал `#FFD166` давал 2.55).
  // На главной этот же цвет раньше лежал на фоне карточки, где четырёхсотый
  // уместен, — цвет переехал на заливку вместе со сведением копий (#61).
  limitNotice: 'rgb(var(--color-warning-200))',
} as const;

export function resolveConnectButtonAccent(isAtDeviceLimit: boolean): ConnectButtonAccent {
  if (isAtDeviceLimit) {
    // Упёрлись в лимит — заливка гасится прозрачностью (то же, что делали
    // прежние литералы `#2B4A85`/`#24407A`: акцент, подмешанный к фону
    // карточки, — только теперь это считает браузер, а не автор), свечение
    // снимается совсем. Вместе с `cursor-not-allowed` и подписью «лимит
    // достигнут» состояние остаётся отличимым от рабочего, а звать в него уже
    // незачем.
    return {
      background:
        'linear-gradient(135deg, rgba(var(--color-accent-500), 0.55), rgba(var(--color-accent-700), 0.55))',
      boxShadow: 'none',
      iconBackground: `rgba(${ON_ACCENT}, 0.12)`,
      ...ON_FILL,
    };
  }

  return {
    background:
      'linear-gradient(135deg, rgb(var(--color-accent-500)), rgb(var(--color-accent-700)))',
    boxShadow: '0 6px 24px rgba(var(--color-accent-500), 0.38)',
    iconBackground: `rgba(${ON_ACCENT}, 0.18)`,
    ...ON_FILL,
  };
}
