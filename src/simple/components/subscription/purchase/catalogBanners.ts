/**
 * Какие предупреждения показывает секция каталога тарифов (задача #71).
 *
 * ⚠️ Модуль чистый: ни React, ни `@/api`, ни `@/store`. Иначе правило нечем
 * проверить — компонентных тестов в проекте не бывает
 * (docs/architecture/two-modes.md, раздел «Тесты»).
 *
 * ⚠️ Зачем модуль вообще. Владелец увидел на стенде ДВА предупреждения подряд,
 * говорящие одно и то же:
 *
 *   - наше «Ваш тариф больше не поддерживается. Выберите другой тариф» (#69);
 *   - апстримное «Подписка истекла. Выберите тариф ниже» (`expiredBanner`).
 *
 * Условия у них были независимые — каждое сидело в своей ветке разметки, — и у
 * подписки со снятым тарифом срабатывали оба. Оставляем ОДИН, более точный: он
 * называет причину, а не только следствие. Решение переехало сюда, потому что
 * два независимых условия в разметке ровно так и разъезжаются: увидеть это
 * можно только глазами на стенде, а стенд показывает не все состояния.
 */

export interface CatalogBannersInput {
  /**
   * Тариф подписки снят с продажи — решение принял ВЫЗЫВАЮЩИЙ экран
   * (`resolvePaymentPlan`, поле `unsupportedTariffBanner`). Своего условия у
   * секции нет: человеку без подписки это сообщение — ложь.
   */
  unsupportedTariff: boolean;
  /** `purchase-options.subscription_is_expired` — признак от бэкенда. */
  subscriptionExpired: boolean;
  /** Человек уже выбрал тариф и стоит на форме оплаты. */
  tariffSelected: boolean;
}

export interface CatalogBanners {
  unsupportedTariff: boolean;
  expired: boolean;
}

/**
 * ⚠️ «Подписка истекла» глушится ВХОДОМ `unsupportedTariff`, а не видимостью
 * первого баннера, и перепутать эти две вещи стоит дороже всего.
 *
 * Баннер про снятый тариф прячется, когда человек выбрал тариф: на форме оплаты
 * речь идёт про новый тариф, и напоминание про старый там лишнее (#69). Считай
 * мы глушение по видимости — на форме вместо исчезнувшего баннера ВСПЛЫЛ бы
 * «подписка истекла», и два баннера превратились бы в один мигающий: он
 * появлялся бы ровно в тот момент, когда человек уже принял решение.
 *
 * Обратный случай задача оговаривает прямо и он сохраняется: у истёкшей
 * подписки с ЖИВЫМ тарифом (`unsupportedTariff === false` — так приходит
 * витрина `/subscription/purchase`) апстримный блок работает как работал,
 * включая показ на форме покупки.
 */
export function resolveCatalogBanners(input: CatalogBannersInput): CatalogBanners {
  return {
    unsupportedTariff: input.unsupportedTariff && !input.tariffSelected,
    expired: input.subscriptionExpired && !input.unsupportedTariff,
  };
}
