/**
 * ЕДИНСТВЕННОЕ правило подписи срока подписки (задача #71).
 *
 * ⚠️ Модуль чистый: ни React, ни `@/*`. Переводчик приходит аргументом, а не
 * хуком, — иначе правило нечем проверить: компонентных тестов в проекте не
 * бывает (docs/architecture/two-modes.md, раздел «Тесты»).
 *
 * ⚠️ ВЫБОР КОНВЕНЦИИ. Их было две, и на стенде они стояли рядом: экран оплаты
 * писал «30 дней», форма покупки того же тарифа — «1 месяц». Смешивать нельзя,
 * и оставлена подпись ДНЯМИ. Причины, по порядку веса:
 *
 *   1. «1 месяц» — это `TariffPeriod.label`, строка от бэкенда, и живёт она
 *      ТОЛЬКО у периодов тарифа. На пути обычного продления цены приходят
 *      `RenewalOption`, а у него из всей длины срока есть единственное поле
 *      `period_days` (`src/types/index.ts:180-186`) — ни `label`, ни `months`.
 *      То есть конвенция «1 месяц» на половине путей недостижима вовсе, и
 *      получить её можно было бы только выдумав месяцы из дней. Конвенция
 *      днями, наоборот, выводится из обоих источников без домысла.
 *   2. Дни — ровно то число, которое уходит в оплату: и
 *      `renewSubscription(periodDays, …)`, и `purchaseTariff(…, days, …)`
 *      принимают дни. Подпись совпадает с тем, за что списывают деньги.
 *   3. Ключ `subscription.days` — АПСТРИМНЫЙ и уже переведён на все языки,
 *      причём с плюральными формами (`days_one` / `days_few` / `days_many`).
 *      Своей строки задача не заводит, а «1 день» вместо «1 дней» получается
 *      сам собой — прежняя разметка экрана оплаты склеивала число со словом
 *      руками и в единице числа врала.
 *
 * Цена решения названа прямо: подпись «1 месяц», которую бэкенд считает сам,
 * на экранах больше не показывается — вместо неё «30 дней».
 */

/** Апстримный ключ с плюральными формами: `{{count}} день / дня / дней`. */
export const PERIOD_LABEL_KEY = 'subscription.days';

/**
 * Ровно та часть `t`, которая нужна подписи.
 *
 * Узкий тип, а не `TFunction`: модуль обязан оставаться чистым, а тесту —
 * подсунуть свою функцию и увидеть, каким ключом её позвали.
 */
export type PeriodLabelTranslator = (key: string, options: { count: number }) => string;

/** Подпись срока: «30 дней», «1 день», «180 дней». */
export function formatPeriodLabel(days: number, translate: PeriodLabelTranslator): string {
  return translate(PERIOD_LABEL_KEY, { count: days });
}
